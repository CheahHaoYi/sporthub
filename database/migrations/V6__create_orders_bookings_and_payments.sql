CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL UNIQUE,
    account_user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    idempotency_key TEXT NOT NULL,
    request_fingerprint TEXT NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    demographic_discount_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (demographic_discount_total >= 0),
    coupon_discount_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (coupon_discount_total >= 0),
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'SGD' CHECK (currency = 'SGD'),
    order_status TEXT NOT NULL CHECK (order_status IN ('CONFIRMED','CANCELLED')),
    payment_status TEXT NOT NULL CHECK (payment_status IN ('SIMULATED_SUCCESS','SIMULATED_FAILED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(account_user_id, idempotency_key)
);
CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    account_user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    facility_slot_id BIGINT NOT NULL REFERENCES facility_slots(id) ON DELETE RESTRICT,
    customer_profile_id BIGINT NOT NULL,
    booking_status TEXT NOT NULL CHECK (booking_status IN ('CONFIRMED','CANCELLED')),
    base_price NUMERIC(12,2) NOT NULL CHECK (base_price >= 0),
    demographic_category_snapshot TEXT NOT NULL CHECK (demographic_category_snapshot IN ('CHILD','ADULT','SENIOR')),
    discount_percentage_snapshot NUMERIC(5,2) NOT NULL CHECK (discount_percentage_snapshot BETWEEN 0 AND 100),
    discount_amount_snapshot NUMERIC(12,2) NOT NULL CHECK (discount_amount_snapshot >= 0),
    final_price NUMERIC(12,2) NOT NULL CHECK (final_price >= 0),
    booked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(account_user_id, customer_profile_id) REFERENCES customer_profiles(account_user_id, id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_bookings_confirmed_slot ON bookings(facility_slot_id) WHERE booking_status = 'CONFIRMED';
CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    item_type TEXT NOT NULL CHECK (item_type IN ('BOOKING','PRODUCT')),
    product_id BIGINT REFERENCES products(id) ON DELETE RESTRICT,
    booking_id BIGINT UNIQUE REFERENCES bookings(id) ON DELETE RESTRICT,
    description_snapshot TEXT NOT NULL,
    sku_snapshot TEXT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    line_subtotal NUMERIC(12,2) NOT NULL CHECK (line_subtotal >= 0),
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    line_total NUMERIC(12,2) NOT NULL CHECK (line_total >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((item_type = 'BOOKING' AND booking_id IS NOT NULL AND product_id IS NULL AND quantity = 1)
        OR (item_type = 'PRODUCT' AND product_id IS NOT NULL AND booking_id IS NULL))
);
CREATE TABLE coupon_redemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL REFERENCES coupons(id) ON DELETE RESTRICT,
    account_user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT,
    discount_amount NUMERIC(12,2) NOT NULL CHECK (discount_amount >= 0),
    redeemed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT,
    payment_reference TEXT NOT NULL UNIQUE,
    provider TEXT NOT NULL DEFAULT 'SIMULATED' CHECK (provider = 'SIMULATED'),
    payment_status TEXT NOT NULL CHECK (payment_status IN ('SIMULATED_SUCCESS','SIMULATED_FAILED')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
