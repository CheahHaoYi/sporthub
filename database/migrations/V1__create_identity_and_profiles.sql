CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('CUSTOMER', 'ADMIN')),
    account_status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE', 'SUSPENDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_app_users_email_lower ON app_users (LOWER(email));

CREATE TABLE customer_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    profile_type TEXT NOT NULL CHECK (profile_type IN ('SELF', 'DEPENDENT')),
    full_name TEXT NOT NULL CHECK (BTRIM(full_name) <> ''),
    date_of_birth DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_customer_profile_owner_id UNIQUE (account_user_id, id)
);
CREATE UNIQUE INDEX uq_customer_profiles_one_self ON customer_profiles(account_user_id) WHERE profile_type = 'SELF';
