CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','CHECKED_OUT')),
    coupon_id BIGINT REFERENCES coupons(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_carts_one_active_per_account ON carts(account_user_id) WHERE status = 'ACTIVE';
CREATE TABLE facility_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT NOT NULL REFERENCES facility_resources(id) ON DELETE RESTRICT,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    base_price NUMERIC(12,2) NOT NULL CHECK (base_price >= 0),
    capacity INTEGER NOT NULL DEFAULT 1 CHECK (capacity = 1),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (ends_at > starts_at),
    UNIQUE(resource_id, starts_at, ends_at)
);
CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
    item_type TEXT NOT NULL CHECK (item_type IN ('BOOKING','PRODUCT')),
    facility_slot_id BIGINT REFERENCES facility_slots(id) ON DELETE RESTRICT,
    customer_profile_id BIGINT REFERENCES customer_profiles(id) ON DELETE RESTRICT,
    product_id BIGINT REFERENCES products(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((item_type = 'BOOKING' AND facility_slot_id IS NOT NULL AND customer_profile_id IS NOT NULL AND product_id IS NULL AND quantity = 1)
        OR (item_type = 'PRODUCT' AND product_id IS NOT NULL AND facility_slot_id IS NULL AND customer_profile_id IS NULL AND quantity >= 1))
);
