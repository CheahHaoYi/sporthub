CREATE TABLE discount_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_category TEXT NOT NULL CHECK (customer_category IN ('CHILD','ADULT','SENIOR')),
    min_age_inclusive INTEGER NOT NULL CHECK (min_age_inclusive >= 0),
    max_age_inclusive INTEGER,
    discount_percentage NUMERIC(5,2) NOT NULL CHECK (discount_percentage BETWEEN 0 AND 100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (max_age_inclusive IS NULL OR max_age_inclusive >= min_age_inclusive),
    UNIQUE (customer_category)
);
CREATE TABLE coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    discount_type TEXT NOT NULL CHECK (discount_type IN ('PERCENTAGE','FIXED')),
    discount_value NUMERIC(12,2) NOT NULL CHECK (discount_value > 0),
    minimum_eligible_subtotal NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (minimum_eligible_subtotal >= 0),
    maximum_discount_amount NUMERIC(12,2) CHECK (maximum_discount_amount IS NULL OR maximum_discount_amount >= 0),
    valid_from TIMESTAMPTZ NOT NULL,
    valid_until TIMESTAMPTZ NOT NULL,
    total_redemption_limit INTEGER CHECK (total_redemption_limit IS NULL OR total_redemption_limit >= 0),
    per_customer_redemption_limit INTEGER NOT NULL DEFAULT 1 CHECK (per_customer_redemption_limit > 0),
    redeemed_count INTEGER NOT NULL DEFAULT 0 CHECK (redeemed_count >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (valid_until > valid_from),
    CHECK (discount_type <> 'PERCENTAGE' OR discount_value <= 100),
    CHECK (total_redemption_limit IS NULL OR redeemed_count <= total_redemption_limit)
);
CREATE UNIQUE INDEX uq_coupons_code_lower ON coupons (LOWER(code));
